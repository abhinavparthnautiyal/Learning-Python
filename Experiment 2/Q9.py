"""Write a Python program that accepts a person's age as input and determines whether the person is eligible to vote.

If the age is 18 or above, print:
"Your eligible to vote"

Otherwise, print:
"Your not eligible to vote" """
age=int(input("Enter your age:"))
if age==18 or age>=18 :
    print("Your eligible to vote")
else :
    print("Your not eligible to vote")
